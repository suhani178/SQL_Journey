-- Day 5 Practice

-- AND

SELECT *
FROM EMP
WHERE DEPTNO = 20
AND SAL > 1500;

SELECT ENAME
FROM EMP
WHERE DEPTNO = 20
AND SAL > 2500;

-- OR

SELECT *
FROM EMP
WHERE DEPTNO = 10
OR DEPTNO = 30;

SELECT ENAME
FROM EMP
WHERE DEPTNO = 10
OR DEPTNO = 20;

-- NOT

SELECT *
FROM EMP
WHERE NOT DEPTNO = 20;

SELECT ENAME
FROM EMP
WHERE JOB <> 'CLERK';

-- IN

SELECT *
FROM EMP
WHERE DEPTNO IN (10,20,30);

SELECT ENAME
FROM EMP
WHERE DEPTNO IN (10,20);

SELECT *
FROM EMP
WHERE JOB IN ('CLERK','MANAGER','ANALYST');

-- BETWEEN

SELECT *
FROM EMP
WHERE SAL BETWEEN 1000 AND 3000;

SELECT ENAME
FROM EMP
WHERE SAL BETWEEN 1500 AND 5000;

SELECT ENAME, SAL
FROM EMP
WHERE SAL BETWEEN 800 AND 3000;

-- ORDER BY

SELECT *
FROM EMP
ORDER BY SAL ASC;

SELECT *
FROM EMP
ORDER BY SAL DESC;

SELECT ENAME
FROM EMP
ORDER BY ENAME ASC;

SELECT ENAME
FROM EMP
ORDER BY ENAME DESC;

-- Mixed Queries

SELECT ENAME
FROM EMP
WHERE DEPTNO = 20
AND SAL BETWEEN 2000 AND 5000;

SELECT *
FROM EMP
WHERE (DEPTNO = 10 OR DEPTNO = 20)
AND SAL > 2500;

SELECT *
FROM EMP
WHERE DEPTNO <> 30
AND SAL > 1000;

SELECT ENAME, JOB
FROM EMP
WHERE DEPTNO IN (10,20);

SELECT *
FROM EMP
ORDER BY DEPTNO;

SELECT ENAME
FROM EMP
WHERE SAL BETWEEN 1000 AND 5000
AND DEPTNO <> 30;
