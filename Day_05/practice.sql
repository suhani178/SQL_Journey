SELECT *
FROM EMPLOYEE
WHERE DEPTNO IN (10, 20, 30);

SELECT *
FROM EMPLOYEE
WHERE JOB IN ('CLERK', 'MANAGER');

SELECT *
FROM EMPLOYEE
WHERE DEPTNO NOT IN (10, 20);

SELECT *
FROM EMPLOYEE
WHERE SAL BETWEEN 2000 AND 4000;

SELECT *
FROM EMPLOYEE
WHERE SAL NOT BETWEEN 2000 AND 4000;

SELECT ENAME, SAL
FROM EMPLOYEE
WHERE SAL BETWEEN 1500 AND 3000;

SELECT *
FROM EMPLOYEE
WHERE DEPTNO IN (10, 20)
AND SAL > 2000;

SELECT *
FROM EMPLOYEE
WHERE DEPTNO NOT IN (10, 20)
AND SAL > 1500;

SELECT *
FROM EMPLOYEE
WHERE SAL BETWEEN 2000 AND 4000
AND DEPTNO = 20;

SELECT ENAME, DEPTNO, SAL
FROM EMPLOYEE
WHERE DEPTNO IN (10, 30)
AND SAL BETWEEN 1500 AND 3500;

SELECT *
FROM EMPLOYEE
WHERE (DEPTNO IN (10, 20) AND SAL > 2000)
OR SAL BETWEEN 4000 AND 5000;