-- Day 9 Practice

SELECT DEPTNO, AVG(SAL)
FROM EMP
GROUP BY DEPTNO
HAVING AVG(SAL) > 2000;

SELECT DEPTNO, SUM(SAL)
FROM EMP
GROUP BY DEPTNO
HAVING SUM(SAL) > 10000;

SELECT DEPTNO, COUNT()
FROM EMP
GROUP BY DEPTNO
HAVING COUNT() > 3;

SELECT JOB, COUNT()
FROM EMP
GROUP BY JOB
HAVING COUNT() > 2;

SELECT JOB, AVG(SAL)
FROM EMP
GROUP BY JOB
HAVING AVG(SAL) > 2000;

SELECT DEPTNO, MAX(SAL)
FROM EMP
GROUP BY DEPTNO
HAVING MAX(SAL) > 3000;
